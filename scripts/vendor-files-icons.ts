// Run with bun; T3's original files stay untouched. Outputs are shipped, so installation needs neither Bun nor T3.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { runInNewContext } from "node:vm";
import { execFileSync } from "node:child_process";

const root = resolve(import.meta.dirname, ".."), t3 = resolve(process.argv[2] ?? `${process.env.HOME}/my/tools/t3code`);
const revision = execFileSync("git", ["-C", t3, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (revision !== "09a54f01bc0ae83865347a965ced50f8c8ec2953") throw new Error(`Expected T3 09a54f01, got ${revision}`);
const modulePath = Bun.resolveSync("@pierre/trees", `${t3}/apps/web`);
const { getBuiltInSpriteSheet } = await import(pathToFileURL(modulePath).href);
const { T3_PIERRE_ICONS } = await import(pathToFileURL(`${t3}/apps/web/src/pierre-icons.ts`).href);
const library = readFileSync(`${dirname(modulePath)}/builtInIcons.js`, "utf8");
const source = library.replace(/^export \{[^\n]+\};?$/gm, "");
const maps = runInNewContext(`${source}\n({ names: BUILT_IN_FILE_NAME_TOKENS, extensions: {...BUILT_IN_FILE_EXTENSION_TOKENS,...COMPLETE_EXTENSION_OVERRIDES} })`);
const builtin = values => Object.fromEntries(Object.entries(values).map(([key, token]) => [key, `file-tree-builtin-${token}`]));
const names = { ...builtin(maps.names), ...T3_PIERRE_ICONS.byFileName };
const extensions = { ...builtin(maps.extensions), ...T3_PIERRE_ICONS.byFileExtension };
const icons = `${root}/shared/icons/pierre`;
mkdirSync(icons, { recursive: true });
let count = 0;
const sprite = getBuiltInSpriteSheet("complete") + T3_PIERRE_ICONS.spriteSheet;
for (const [, attrs, body] of sprite.matchAll(/<symbol\b([^>]+)>([\s\S]*?)<\/symbol>/g)) {
  const id = attrs.match(/\bid="([^"]+)"/)?.[1];
  if (!id) throw new Error("A Pierre symbol has no id");
  const shape = body.replace(/\sstyle="[^"]*"/g, "").replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"');
  writeFileSync(`${icons}/${id}.svg`, `<svg xmlns="http://www.w3.org/2000/svg"${attrs.replace(/\s*id="[^"]+"/, "")} fill="currentColor">${shape}</svg>\n`);
  count++;
}
writeFileSync(`${root}/shared/pierre-icons-data.js`, `// Generated by scripts/vendor-files-icons.ts from T3 ${revision} and @pierre/trees 1.0.0-beta.6.\nexport const PIERRE_NAMES = ${JSON.stringify(names, null, 2)};\nexport const PIERRE_EXTENSIONS = ${JSON.stringify(extensions, null, 2)};\n`);
writeFileSync(`${icons}/NOTICE`, "Shapes from @pierre/trees 1.0.0-beta.6 (Apache-2.0) and T3 Code 09a54f01 (MIT). Colors are supplied by the layout theme. See LICENSE-pierre and LICENSE-t3code.\n\n" + readFileSync(resolve(dirname(modulePath), "../NOTICE.md"), "utf8"));
writeFileSync(`${icons}/LICENSE-pierre`, readFileSync(resolve(dirname(modulePath), "../LICENSE.md")));
writeFileSync(`${icons}/LICENSE-t3code`, readFileSync(`${t3}/LICENSE`));
console.log(`Generated ${count + 1} Pierre/T3 icon shapes, ${Object.keys(names).length} names, ${Object.keys(extensions).length} extensions.`);
