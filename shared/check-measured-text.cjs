const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const kit = require("./check-kit.js"), element = kit.elements(), { find } = kit;
let zoom = 1, notices = 0;
const cx = { notify() { notices++; } }, view = {}, tips = [];
const c = vm.createContext({ div: element, settings: () => ({ zoom }), Popup: { new: (id, trigger) => element().id(id).child(trigger) },
  tip: (_v, _t, id, label, trigger, options) => { tips.push({ id, label, options }); return trigger; }, tipCard: (_t, id) => element().id(id), FADE: {} });
vm.runInContext(kit.strip(fs.readFileSync(__dirname + '/measured-text.js', 'utf8')), c);
let node = c.nameText(view, 'title', 'iiii', { size: 14, weight: 'medium' });
assert.equal(c.isTextCut(view, 'title'), false, 'unmeasured names read as whole');
find(node, 'text-name-title').handlers.on_size_change({ width: 24 }, cx);
find(node, 'text-measure-title').handlers.on_size_change({ width: 16 }, cx);
assert.equal(c.isTextCut(view, 'title'), false, 'short narrow glyphs fit');
const initial = notices;
find(node, 'text-name-title').handlers.on_size_change({ width: 24 }, cx);
find(node, 'text-measure-title').handlers.on_size_change({ width: 16 }, cx);
assert.equal(notices, initial, 'identical layout reports do not request another render');
node = c.nameText(view, 'title', 'WWWW', { size: 14, weight: 'medium' });
assert.equal(notices, initial, 'constructing a render tree never measures or notifies');
find(node, 'text-measure-title').handlers.on_size_change({ width: 48 }, cx);
assert.equal(c.isTextCut(view, 'title'), true, 'equal character counts can have different measured widths');
const natural = find(node, 'text-measure-title');
assert.equal(natural.style.h, 0); assert.equal(natural.style.truncate, undefined);
assert.equal(natural.style.text_size, 14); assert.ok('font_medium' in natural.style, 'the natural copy owns its text style');
const ancestors = (root, target, chain = []) => root === target ? chain : !root || typeof root !== 'object' ? undefined : root.items.map(child => ancestors(child, target, [...chain, root])).find(Boolean);
assert.ok(ancestors(node, natural).every(parent => !('truncate' in parent.style)), 'the natural copy must not inherit ellipsis from its ancestors');
assert.ok(node.items.some(child => child !== natural && child?.style && 'truncate' in child.style), 'only the visible text child is truncated');
zoom = 2;
find(node, 'text-name-title').handlers.on_size_change({ width: 48 }, cx);
find(node, 'text-measure-title').handlers.on_size_change({ width: 96 }, cx);
assert.equal(notices, initial + 1, 'zoom-normalized widths remain stable');
assert.equal(c.isTextCut(view, 'title', { shown: false }), true, 'an icon or ellipsis hides the name');
c.measuredTooltip(view, {}, 'title', 'Run WWWW', element(), { action: 'run', below: true });
assert.equal(tips.at(-1).label, 'Run WWWW'); assert.equal(tips.at(-1).options.action, 'run');
find(node, 'text-name-title').handlers.on_size_change({ width: 100 }, cx);
const before = tips.length;
c.measuredTooltip(view, {}, 'title', 'Run WWWW', element());
assert.equal(tips.length, before, 'whole names have no tooltip');
c.measuredTooltip(view, {}, 'title', 'Run WWWW', element(), { shown: false });
assert.equal(tips.length, before + 1, 'collapsed controls retain their tooltip');
const events = [], trigger = element().on_click(() => events.push('click'));
view.details = 'title'; view.detailsIn = true;
let named = c.named(view, { chrome: '#111', foreground: '#fff', border: '#333' }, 'title', 'WWWW', trigger, {
  at: 24, onHover: (on, cut) => events.push([on, cut]), onMove: e => events.push(e),
});
named.handlers.on_hover(true, cx); named.handlers.on_mouse_move('move'); named.handlers.on_click();
assert.deepEqual(events, [[true, false], 'move', 'click'], 'named adds measured hover without replacing caller events');
assert.equal(find(named, 'details-title').style.left, 15, 'the custom Popup keeps its name-aligned anchor');
assert.equal(find(named, 'details-card-title').style.opacity, 1);
view.detailsIn = false;
named = c.named(view, {}, 'title', 'WWWW', element(), { shown: false, onHover: (on, cut) => events.push([on, cut]) });
named.handlers.on_hover(true, cx);
assert.deepEqual(events.at(-1), [true, true]);
assert.equal(find(named, 'details-card-title').style.top, -4, 'the existing leaving transition survives');
console.log('ok: measured names use actual text/container widths, zoom, unchanged-size guards and conditional tips');
